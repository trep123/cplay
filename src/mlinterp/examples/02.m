% 示例 2：矩阵运算与线性方程组
% 演示矩阵乘法、左除求解 Ax=b、求逆、行列式与特征值
A = [4 -2 1; -2 4 -2; 1 -2 4]   % 对称正定矩阵
B = [1 0 2; 0 1 0; 3 0 1];
% 矩阵乘法（按线性代数规则）
C = A * B
% 逐元素乘法（注意点号）
D = A .* B
% 求解线性方程组 A*x = b
b = [11; -16; 17];
x = A \ b                  % 推荐写法：左除
% 验证：残差应接近 0
residual = norm(A*x - b)
% 矩阵的逆与行列式
Ainv = inv(A)
detA = det(A)
% 用逆矩阵求解（与左除结果相同，但数值上不推荐）
x2 = Ainv * b
% 特征值与特征向量：A*V = V*D
[V, L] = eig(A);
lambda = diag(L)
% 验证第一个特征对
err = norm(A*V(:,1) - lambda(1)*V(:,1))
fprintf('转置后迹 trace(A'') = %g\n', trace(A'));
